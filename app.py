def display_location(r):
    return r.get("location") or r.get("address") or r.get("area", t["unknown"])

def region_name(r):
    return r.get("province") or r.get("area", t["unknown"])

def display_price(r):
    if not r.get("price"):
        return t["unknown"]
    return r["price"]

def rating_text(r):
    rating = current_rating(r)
    return f"{rating:.1f}/5" if rating is not None else t["not_rated"]

def category_display(r):
    return CATEGORY_NAMES.get(r["category"], r["category"])

def reviews_for(name):
    return [x for x in st.session_state.reviews if x["restaurant"] == name]

def current_rating(r):
    submitted = reviews_for(r["name"])
    count = int(r.get("base_reviews", 0) or 0)
    base_rating = r.get("rating")
    if count > 0 and base_rating is not None:
        total = float(base_rating) * count + sum(x["rating"] for x in submitted)
        return round(total / (count + len(submitted)), 1)
    if submitted:
        return round(sum(x["rating"] for x in submitted) / len(submitted), 1)
    if base_rating is not None:
        return float(base_rating)
    return None

def review_count(r):
    return int(r.get("base_reviews", 0) or 0) + len(reviews_for(r["name"]))

def price_match(r, choice):
    if choice == t["budget"]:
        return r.get("price_level") == "low"
    if choice == t["mid"]:
        return r.get("price_level") in ("low", "mid")
    return True

