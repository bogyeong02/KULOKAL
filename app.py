def reviews_for(name):
    return [x for x in st.session_state.reviews if x["restaurant"] == name]

def current_rating(r):
    submitted = reviews_for(r["name"])
    count = int(r.get("base_reviews", 0) or 0)
    base_rating = r.get("rating")
    if count > 0 and base_rating is not None:
        total = float(base_rating) * count + sum(x["rating"] for x in submitted)
        return round(total / (count + len(submitted)), 1)
    if submitted:
        return round(sum(x["rating"] for x in submitted) / len(submitted), 1)
    if base_rating is not None:
        return float(base_rating)
    return None

def review_count(r):
    return int(r.get("base_reviews", 0) or 0) + len(reviews_for(r["name"]))

